#!/bin/bash
# Build QuickRecorder + DMG with Command Line Tools only (no Xcode / actool / xcodebuild).
# The fork installs side by side with the upstream app: own bundle id + name, Sparkle auto-checks off
# (otherwise Sparkle would "update" it to the upstream build). Override via env vars below.
# Output: cli-build/dist/<APP_NAME> <version>.dmg
set -euo pipefail
cd "$(dirname "$0")"
ROOT=$PWD
PKG=$ROOT/cli-build
SRC=$ROOT/QuickRecorder
ASSETS=$SRC/Assets.xcassets

APP_NAME=${APP_NAME:-"QuickRecorder Fork"}
BUNDLE_ID=${BUNDLE_ID:-"com.phatv1.QuickRecorder"}
ARCH=${ARCH:-arm64}
VERSION=$(grep -m1 'MARKETING_VERSION' QuickRecorder.xcodeproj/project.pbxproj | sed -E 's/.*= *([^;]+);/\1/')
BUILD_NUM=$(grep -m1 'CURRENT_PROJECT_VERSION' QuickRecorder.xcodeproj/project.pbxproj | sed -E 's/.*= *([^;]+);/\1/')
DIST=$PKG/dist
APP="$DIST/$APP_NAME.app"
DMG="$DIST/$APP_NAME $VERSION.dmg"

echo "==> Resolving packages"
swift package --package-path "$PKG" resolve

echo "==> Patching dependency checkouts for Command Line Tools"
python3 - "$PKG/.build/checkouts/KeyboardShortcuts/Sources/KeyboardShortcuts" <<'EOF'
import pathlib, re, sys
root = pathlib.Path(sys.argv[1])
for f in root.rglob("*.swift"):
    s = original = f.read_text()
    # #Preview needs the PreviewsMacros plugin, which ships only with Xcode.
    while (i := s.find("#Preview")) != -1:
        j = s.index("{", i); depth = 0
        for k in range(j, len(s)):
            depth += {"{": 1, "}": -1}.get(s[k], 0)
            if depth == 0: break
        s = s[:i] + s[k + 1:]
    # SwiftPM's Bundle.module looks in the .app root, which codesign refuses; read from Contents/Resources.
    s = s.replace("bundle: .module", 'bundle: Bundle(url: Bundle.main.resourceURL!.appendingPathComponent("KeyboardShortcuts_KeyboardShortcuts.bundle")) ?? .main')
    if s != original: f.chmod(0o644); f.write_text(s)
EOF

echo "==> Generating asset-catalog shim"
mkdir -p "$PKG/Shim"
python3 - "$ASSETS" "$PKG/Shim/AssetShim.swift" <<'EOF'
import json, pathlib, re, sys
assets, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
def camel(n):
    parts = re.split(r"[_\-. ]", n); s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return s[:1].lower() + s[1:]
def rgba(c):
    comp = c["components"]; v = lambda x: int(x, 16) / 255 if x.startswith("0x") else float(x)
    space = ".displayP3" if c.get("color-space") == "display-p3" else ".sRGB"
    return f"Color({space}, red: {v(comp['red']):.4f}, green: {v(comp['green']):.4f}, blue: {v(comp['blue']):.4f}, opacity: {v(comp['alpha']):.4f})"
colors, templates, images = [], [], []
for cs in sorted(assets.rglob("*.colorset")):
    entries = [e for e in json.load(open(cs / "Contents.json"))["colors"] if "color" in e]
    if not entries: continue  # AccentColor: empty -> system accent
    light = next(e for e in entries if "appearances" not in e)["color"]
    dark = next((e["color"] for e in entries if "appearances" in e), light)
    colors.append((camel(cs.stem), rgba(light), rgba(dark)))
for iset in sorted(assets.rglob("*.imageset")):
    images.append(iset.stem)
    if json.load(open(iset / "Contents.json")).get("properties", {}).get("template-rendering-intent") == "template":
        templates.append(iset.stem)
L = ["// Generated by build-cli.sh: stand-ins for Xcode's asset-catalog symbols (actool is Xcode-only).",
     "import SwiftUI", "import AppKit", "",
     "private func dynamicColor(_ light: Color, _ dark: Color) -> Color {",
     "    Color(NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .vibrantDark]) != nil ? NSColor(dark) : NSColor(light) })",
     "}", "", "extension Color {"]
L += [f"    static let {n} = dynamicColor({l}, {d})" for n, l, d in colors]
L += ["}", "", "extension ShapeStyle where Self == Color {"]
L += [f"    static var {n}: Color {{ Color.{n} }}" for n, _, _ in colors]
L += ["}", "", "extension NSImage {"]
L += [f"    static var {camel(n)}: NSImage {{ cliAsset(\"{n}\") ?? NSImage() }}" for n in images]
L += ["}", "",
      f"private let templateAssets: Set<String> = {json.dumps(templates)}",
      "/// Loose catalog images copied to Contents/Resources as <name>.tiff / <name>.pdf.",
      "func cliAsset(_ name: String) -> NSImage? {",
      "    for ext in [\"tiff\", \"pdf\"] {",
      "        if let url = Bundle.main.url(forResource: name, withExtension: ext), let image = NSImage(contentsOf: url) {",
      "            image.isTemplate = templateAssets.contains(name)",
      "            return image",
      "        }",
      "    }",
      "    return nil",
      "}", "",
      "extension Image {",
      "    /// Shadows SwiftUI's Image(_:bundle:) inside this module so catalog names resolve to the loose files.",
      "    init(_ name: String) {",
      "        if let image = cliAsset(name) { self.init(nsImage: image) } else { self.init(name, bundle: nil) }",
      "    }",
      "}", "",
      "extension Label where Title == Text, Icon == Image {",
      "    init(_ title: LocalizedStringKey, image name: String) {",
      "        self.init { Text(title) } icon: { Image(name) }",
      "    }",
      "}"]
out.write_text("\n".join(L) + "\n")
EOF

echo "==> Building ($ARCH, release)"
swift build --package-path "$PKG" -c release --arch "$ARCH"
BIN=$(swift build --package-path "$PKG" -c release --arch "$ARCH" --show-bin-path)

echo "==> Assembling $APP"
rm -rf "$APP"; mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks"
cp "$BIN/QuickRecorder" "$APP/Contents/MacOS/QuickRecorder"
ditto "$BIN/Sparkle.framework" "$APP/Contents/Frameworks/Sparkle.framework"
for b in "$BIN"/*.bundle; do [ -e "$b" ] && ditto "$b" "$APP/Contents/Resources/$(basename "$b")"; done
for l in "$SRC"/*.lproj; do ditto "$l" "$APP/Contents/Resources/$(basename "$l")"; done
cp "$SRC/Supports/Scriptable.sdef" "$APP/Contents/Resources/"

ICONSET=$(mktemp -d)/AppIcon.iconset; mkdir -p "$ICONSET"
cp "$ASSETS"/AppIcon.appiconset/icon_*.png "$ICONSET/"
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/AppIcon.icns"
iconutil -c icns "$ASSETS/Others/qmaIcon.iconset" -o "$APP/Contents/Resources/qmaIcon.icns"

find "$ASSETS" -name '*.imageset' -print0 | while IFS= read -r -d '' set; do
    name=$(basename "$set" .imageset); out="$APP/Contents/Resources/$name"
    svg=$(find "$set" -name '*.svg' | head -1)
    if [ -n "$svg" ]; then swift "$PKG/tools/svg2pdf.swift" "$svg" "$out.pdf" >/dev/null; continue; fi
    # 1x first, then 2x -> one multi-resolution TIFF; light appearance only.
    pngs=$(python3 -c '
import json, sys
d = json.load(open(sys.argv[1] + "/Contents.json"))
imgs = [i for i in d["images"] if i.get("filename") and "appearances" not in i]
imgs.sort(key=lambda i: i.get("scale", "1x"))
print("\n".join(sys.argv[1] + "/" + i["filename"] for i in imgs))' "$set")
    files=(); while IFS= read -r p; do files+=("$p"); done <<< "$pngs"
    if [ ${#files[@]} -ge 2 ]; then tiffutil -cathidpicheck "${files[@]:0:2}" -out "$out.tiff" 2>/dev/null
    else sips -s format tiff "${files[0]}" --out "$out.tiff" >/dev/null; fi
done

python3 - "$SRC/Info.plist" "$APP/Contents/Info.plist" "$APP_NAME" "$BUNDLE_ID" "$VERSION" "$BUILD_NUM" <<'EOF'
import plistlib, sys
src, dst, name, bid, version, build = sys.argv[1:]
p = plistlib.load(open(src, "rb"))
p.update({
    "CFBundleDevelopmentRegion": "en", "CFBundleExecutable": "QuickRecorder", "CFBundleIdentifier": bid,
    "CFBundleInfoDictionaryVersion": "6.0", "CFBundleName": name, "CFBundleDisplayName": name,
    "CFBundlePackageType": "APPL", "CFBundleShortVersionString": version, "CFBundleVersion": build,
    "CFBundleIconFile": "AppIcon", "CFBundleSupportedPlatforms": ["MacOSX"], "LSMinimumSystemVersion": "12.3",
    "NSPrincipalClass": "NSApplication", "NSHighResolutionCapable": True,
    # Mirrors INFOPLIST_KEY_* in project.pbxproj.
    "LSApplicationCategoryType": "public.app-category.utilities", "LSUIElement": True,
    "NSCameraUsageDescription": "QuickRecorder needs this permission to record your camera and mobile device.",
    "NSMicrophoneUsageDescription": "QuickRecorder needs this permission to record your voice.",
    "NSHumanReadableCopyright": "Copyright © 2024 lihaoyun6. All rights reserved.",
    # Upstream's appcast would replace this fork with the upstream build.
    "SUEnableAutomaticChecks": False,
})
plistlib.dump(p, open(dst, "wb"))
EOF

# No hardened runtime: its library validation rejects ad-hoc frameworks (same as build-release.sh's result).
echo "==> Signing (ad-hoc)"
codesign --force --deep --sign - "$APP/Contents/Frameworks/Sparkle.framework"
codesign --force --sign - --entitlements "$SRC/QuickRecorder.entitlements" "$APP"
codesign --verify --deep --strict "$APP"

echo "==> Creating DMG"
STAGE=$(mktemp -d); ditto "$APP" "$STAGE/$APP_NAME.app"; ln -s /Applications "$STAGE/Applications"
rm -f "$DMG"
hdiutil create -volname "$APP_NAME $VERSION" -srcfolder "$STAGE" -ov -format UDZO "$DMG" >/dev/null
rm -rf "$STAGE"
echo "Done: $DMG"
